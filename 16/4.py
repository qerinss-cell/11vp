count = 0
# Неверное начальное значение для произведения
p = 1
# цикл выполнится только 9 раз
for i in range(1, 11):
    x = int(input())
# Задача просит найти количество неотрицательных чисел
    if x >= 0:
        p = p * x
        count = count + 1
if count > 0:
# выводит последнее введённое число
    print(count)
    print(p)
else:
    print("NO")