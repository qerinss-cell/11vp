s = input()
# Нужно меньше 10, иначе программа сделает лишний шаг.
while len(s) < 10:
    # Нужно проверять остаток от деления % на равенство нулю.
    if len(s) % 4 == 0:
        s = s + 'x'

    #  заменить // на % для проверки кратности.
    elif len(s) % 5 == 0:
        s = s + 'y'
    else:
        # По условию 'z' нужно прибавлять слева, а не справа.
        s = 'z' + s


# В задаче требуется добавить символ '@'
s = '@' + s
print(s)