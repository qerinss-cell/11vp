# Максимум среди отрицательных должен начинаться с очень маленького числа.
mx = -1000000
s = 0

# По условию вводится ровно 10 чисел.
for i in range(10):
    x = int(input())
    if x < 0:
        # Нужно накапливать сумму.
        s += x

        # Поиск максимума должен быть тллько для отрицательных чисел
        if x > mx:
            mx = x

print(s)
#  Если отрицательных не было, нужно вывести 'NO'.
print(mx if s != 0 else 'NO')